export function pickRandomDailyEvent(
  excludeIds: Set<string>
): DailyRandomEvent {
  const available = DAILY_RANDOM_EVENTS.filter((e) => !excludeIds.has(e.id));
  const pool = available.length > 0 ? available : DAILY_RANDOM_EVENTS;
  return pool[Math.floor(Math.random() * pool.length)];
}
